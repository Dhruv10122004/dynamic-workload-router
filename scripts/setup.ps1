<#
.SYNOPSIS
  Windows laptop setup (plan sec. 16.1): venv, dependencies, .env with fresh tokens.

.DESCRIPTION
  Re-runnable: never overwrites an existing .env. Prints (does not run) the firewall
  command, which needs an elevated prompt. Builds the dashboard (frontend/dist) when
  Node.js is installed; the controller serves it at http://127.0.0.1:<port>/.

.EXAMPLE
  .\scripts\setup.ps1 -BindIp 192.168.1.10 -EdgeSlots "2;4"
#>
param(
    [string]$BindIp = '',          # LAN or Tailscale IP of this laptop (in addition to 127.0.0.1)
    [string]$EdgeSlots = '2;4',    # Edge slot cores: ";" between slots, "," within a slot
    [int]$Port = 8000
)
. "$PSScriptRoot\dwr-common.ps1"
$root = Get-DwrRoot

# ---- Python 3.10-3.12 ----------------------------------------------------------------
$venvPy = Join-Path $root '.venv\Scripts\python.exe'
if (-not (Test-Path -LiteralPath $venvPy)) {
    $made = $false
    foreach ($v in @('3.12', '3.11', '3.10')) {
        & py "-$v" -c "import sys" 2>$null
        if ($LASTEXITCODE -eq 0) {
            Write-Host "creating .venv with Python $v"
            & py "-$v" -m venv (Join-Path $root '.venv')
            $made = $true
            break
        }
    }
    if (-not $made) { throw 'Need Python 3.10-3.12 via the py launcher (python.org installer).' }
}
& $venvPy -m pip install --quiet --upgrade pip
& $venvPy -m pip install --quiet -r (Join-Path $root 'requirements.txt')
if ($LASTEXITCODE -ne 0) { throw 'pip install failed' }
Write-Host 'dependencies installed' -ForegroundColor Green

# ---- Dashboard build (plan sec. 10): served by the controller from frontend/dist --------
if (Get-Command npm -ErrorAction SilentlyContinue) {
    Push-Location (Join-Path $root 'frontend')
    try {
        # cmd /c: npm writes progress to stderr, which PowerShell 5.1 would treat as an error.
        cmd /c "npm ci --no-audit --no-fund && npm run build"
        if ($LASTEXITCODE -ne 0) { throw "dashboard build failed (npm exit $LASTEXITCODE)" }
    } finally {
        Pop-Location
    }
    Write-Host 'dashboard built: frontend\dist' -ForegroundColor Green
} else {
    Write-Host 'Node.js/npm not found: dashboard not built (the API works without it).' -ForegroundColor Yellow
}

# ---- .env --------------------------------------------------------------------------------
$envPath = Join-Path $root '.env'
if (Test-Path -LiteralPath $envPath) {
    Write-Host ".env exists; left unchanged (delete it to regenerate)"
} else {
    $edgeTok = [guid]::NewGuid().ToString('N'); $fogTok = [guid]::NewGuid().ToString('N')
    $adminTok = [guid]::NewGuid().ToString('N')
    $hosts = '127.0.0.1'
    if ($BindIp) { $hosts = "127.0.0.1,$BindIp" }
    $text = @"
# Generated by scripts\setup.ps1 on $(Get-Date -Format s). Never commit this file.
# ---- Controller
DWR_BIND_HOSTS=$hosts
DWR_PORT=$Port
DWR_CONTROLLER_DATA_DIR=./var/controller
DWR_WORKER_TOKENS=edge-1:$edgeTok,fog-1:$fogTok
DWR_ADMIN_TOKEN=$adminTok
DWR_TEST_MODE=0
DWR_STALE_S=5
# DWR_CONTROLLER_CPUS=     (default: every core not used by a slot)
# DWR_SIM_SLOT_CPUS=       (start.ps1 -Sim; default: two highest free cores)
# ---- Edge worker agent (this laptop)
DWR_WORKER_ID=edge-1
DWR_TIER=edge
DWR_CONTROLLER_URL=http://127.0.0.1:$Port
DWR_WORKER_TOKEN=$edgeTok
DWR_SLOT_CPUS=$EdgeSlots
DWR_MEM_BUDGET_MB=1536
DWR_MEM_FLOOR_MB=512
DWR_DATA_DIR=./var/worker
"@
    [IO.File]::WriteAllText($envPath, $text, (New-Object Text.UTF8Encoding($false)))
    Write-Host "wrote $envPath" -ForegroundColor Green
    Write-Host ""
    Write-Host "For the Linux laptop (scripts/setup.sh prompts): worker id fog-1, token:"
    Write-Host "  $fogTok" -ForegroundColor Cyan
}

# ---- network hints -------------------------------------------------------------------
Write-Host ""
Write-Host "IPv4 addresses of this laptop (use one as -BindIp / in DWR_BIND_HOSTS):"
Get-NetIPAddress -AddressFamily IPv4 -ErrorAction SilentlyContinue |
    Where-Object { $_.IPAddress -ne '127.0.0.1' -and $_.IPAddress -notlike '169.254.*' } |
    ForEach-Object { Write-Host "  $($_.IPAddress)  ($($_.InterfaceAlias))" }
Write-Host ""
Write-Host "Firewall (run once in an ELEVATED PowerShell; use -RemoteAddress 100.64.0.0/10 for Tailscale):"
Write-Host "  New-NetFirewallRule -DisplayName 'DWR controller $Port' -Direction Inbound -Protocol TCP -LocalPort $Port -RemoteAddress LocalSubnet -Action Allow -Profile Private"
Write-Host "Network profile must be Private: Get-NetConnectionProfile"
Write-Host ""
Write-Host "Next: .\scripts\start.ps1   (or -Sim to add a simulated Fog worker on this laptop)"
